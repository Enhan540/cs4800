"""Install commit checks and an all-refs push check without replacing unknown hooks."""

from pathlib import Path
import shlex
import subprocess
import sys


def install_hooks(root, interpreter=None):
    root = Path(root).resolve()
    configured = subprocess.run(["git", "config", "--get", "core.hooksPath"], cwd=root, capture_output=True, text=True, check=False)
    if configured.returncode not in (0, 1) or configured.stdout.strip():
        print("Custom hook configuration preserved; integrate the security checks with that configuration.")
        return 1
    common = subprocess.run(["git", "rev-parse", "--git-common-dir"], cwd=root, capture_output=True, text=True, check=True).stdout.strip()
    directory = Path(common)
    directory = (directory if directory.is_absolute() else root / directory).resolve() / "hooks"
    trusted = ("# Group Planner security commit check", "# Group Planner security push check", "# File generated by pre-commit:")
    for name in ("pre-commit", "pre-push"):
        target = directory / name
        if target.with_name(name + ".legacy").exists() or (target.exists() and not any(marker in target.read_text(encoding="utf-8") for marker in trusted)):
            print("Existing hooks preserved; integrate the security checks before replacing them.")
            return 1
    directory.mkdir(parents=True, exist_ok=True)
    python = shlex.quote(Path(interpreter or sys.executable).as_posix())
    for name, command in (("pre-commit", '"$root/scripts/security_check.py" commit'), ("pre-push", '"$root/scripts/security_push_hook.py" "$@"')):
        label = "commit" if name == "pre-commit" else "push"
        target = directory / name
        target.write_text(f'#!/bin/sh\n# Group Planner security {label} check\nroot=$(git rev-parse --show-toplevel) || exit 1\nexec {python} {command}\n', encoding="utf-8", newline="\n")
        target.chmod(0o755)
    print("Commit and all-refs push security checks installed.")
    return 0


def main():
    return install_hooks(Path(__file__).resolve().parents[1])


if __name__ == "__main__":
    raise SystemExit(main())
